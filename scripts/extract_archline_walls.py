"""Extract wall layer facts from ARCHLine.XP's Italian .set templates.

Usage: python scripts/extract_archline_walls.py "C:/ProgramData/CadLine/ARCHlineXP2024/Templates/Local_Ita/Wall"
The source files are read only. This writes a small Rust catalog and an audit table.
"""

from __future__ import annotations

import hashlib
import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path


def rust_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def category(name: str) -> str:
    upper = name.upper()
    if "EST." in upper or "ESTERNO" in upper:
        return "Exterior"
    if "INTERNO" in upper:
        return "Interior"
    if "CEMENTO" in upper:
        return "Concrete"
    if "LEGNO" in upper or "TIMBER" in upper:
        return "Timber"
    if "MATTONI FORATI" in upper:
        return "HollowBrick"
    return "Generic"


def role(material: str, index: int, count: int) -> tuple[str, str]:
    lower = material.lower()
    if "thermal" in lower or "isolation" in lower or "hoszig" in lower:
        return "InsulationMaterial", "Insulation"
    if "plaster" in lower or "stucco" in lower or "wallpaint" in lower or "wallpaper" in lower:
        return "Plaster", "Finish"
    if "concrete" in lower or "cement" in lower:
        return "Concrete", "Structure"
    if "brick" in lower or "terca" in lower or "masonry" in lower:
        return "Masonry", "Structure"
    if "wood" in lower or "beech" in lower:
        return "Wood", "Structure"
    return "Generic", "Finish" if count > 1 and index in (0, count - 1) else "Structure"


def extract(path: Path) -> tuple[list[dict], list[str]]:
    entries = []
    excluded = []
    for source in sorted(path.glob("*.set")):
        root = ET.parse(source).getroot()
        wall = root.find("./Wall/AttrWall")
        if wall is None:
            excluded.append(f"{source.name}: no wall definition")
            continue
        name = " ".join(wall.find("AttrGen").get("SetName", source.stem).split("\\")[-1].split())
        # U profiles are nonplanar sections and cannot be represented by parallel layers.
        if "U_Profile" in source.name or "Profilo U" in name:
            excluded.append(f"{source.name}: U-shaped section requires a profile model")
            continue
        boundaries = [int(value) for value in wall.get("Wids", "").split(";") if value]
        count = int(wall.get("Nwid", "0"))
        all_materials = [node.text or "" for node in wall.findall("Mats")]
        materials = all_materials[1:]
        if len(boundaries) != count or len(materials) != count or not boundaries or any(
            b <= a for a, b in zip([0] + boundaries[:-1], boundaries)
        ):
            excluded.append(f"{source.name}: inconsistent layer widths or materials")
            continue
        widths = [b - a for a, b in zip([0] + boundaries[:-1], boundaries)]
        group = category(name)
        entry_id = "AL24-" + hashlib.sha256(source.stem.encode()).hexdigest()[:10].upper()
        entries.append(dict(id=entry_id, name=name, group=group, widths=widths, materials=materials,
                            face_material=all_materials[0], source=source.name))
    duplicate_names = {item["name"] for item in entries if sum(e["name"] == item["name"] for e in entries) > 1}
    for item in entries:
        if item["name"] in duplicate_names:
            item["name"] += f" ({item['face_material']})"
    return entries, excluded


def write_catalog(entries: list[dict], dest: Path) -> None:
    lines = ["// Generated by scripts/extract_archline_walls.py from ARCHLine.XP 2024 Italian wall templates.",
             "// Only geometric widths and material labels are retained; no source XML or textures."]
    for index, item in enumerate(entries):
        lines.append(f"const ARCHLINE_LAYERS_{index}: &[LayerSpec] = &[")
        for i, (width, material) in enumerate(zip(item["widths"], item["materials"])):
            material_role, function = role(material, i, len(item["widths"]))
            lines.append(
                f"    LayerSpec {{ role: {material_role}, thickness: {width / 1000:.3f}, function: {function} }},"
            )
        lines.append("];")
        lines.append(f"const ARCHLINE_MATERIALS_{index}: &[&str] = &[")
        lines.extend(f"    {rust_string(material)}," for material in item["materials"])
        lines.append("];")
    lines.append("static ARCHLINE_PRESETS: &[WallPreset] = &[")
    for index, item in enumerate(entries):
        group = item["group"]
        function = "Exterior" if group == "Exterior" else "Interior"
        lines += [
            "    WallPreset {",
            f"        id: {rust_string(item['id'])},",
            "        name_key: None,",
            f"        name: {rust_string('ARCHLine · ' + item['name'])},",
            f"        category: WallPresetCategory::{group},",
            f"        function: WallFunction::{function},",
            f"        layers: ARCHLINE_LAYERS_{index},",
            f"        material_names: Some(ARCHLINE_MATERIALS_{index}),",
            "    },",
        ]
    lines.append("];")
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_audit(entries: list[dict], excluded: list[str], dest: Path) -> None:
    lines = [
        "# ARCHLine.XP wall preset extraction",
        "",
        "Source: `ARCHlineXP2024/Templates/Local_Ita/Wall/*.set` from the installed ARCHLine.XP library.",
        "The source files were read only and are not included in this repository.",
        "Widths in `AttrWall.Wids` are cumulative millimetres; adjacent differences form the layers below.",
        "The first `Mats` entry is the face material; subsequent entries are the layer labels.",
        "ConstructCAD retains the widths and labels. Material colors, hatches, render textures and thermal properties are approximations and should be reviewed before technical use.",
        "Only names that explicitly indicate an exterior wall are assigned the exterior function; other imported walls default to interior and remain editable.",
        "",
        f"Imported: {len(entries)}. Excluded: {len(excluded)}.",
        "",
        "| Category | ARCHLine style | Layers (mm) | Material labels |",
        "| --- | --- | --- | --- |",
    ]
    for item in entries:
        lines.append(
            f"| {item['group']} | {item['name']} | {' + '.join(map(str, item['widths']))} = {sum(item['widths'])} | {' / '.join(item['materials'])} |"
        )
    lines += ["", "## Excluded", ""]
    lines.extend(f"- {item}" for item in excluded)
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("Pass the ARCHLine.XP Wall template directory")
    source = Path(sys.argv[1])
    if not source.is_dir():
        raise SystemExit(f"Not a directory: {source}")
    entries, excluded = extract(source)
    if not entries:
        raise SystemExit("No usable wall presets found")
    root = Path(__file__).resolve().parents[1]
    write_catalog(entries, root / "crates/cc_engine/src/commands/archline_wall_presets.rs")
    write_audit(entries, excluded, root / "docs/archline_wall_presets.md")
    print(f"Imported {len(entries)} wall presets; excluded {len(excluded)}")


if __name__ == "__main__":
    main()
